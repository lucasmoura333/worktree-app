package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const baseTemplate = `# Generated by worktree-app/v1. Views may be customized; this file is created only once.
filters:
  and:
    - file.inFolder("{{folder}}")
    - 'type == "worktree"'
properties:
  slug:
    displayName: Worktree
  front:
    displayName: Frente
  last_savepoint:
    displayName: Último savepoint
  updated_at:
    displayName: Atualizado em
views:
  - type: cards
    name: Ativos
    filters: 'status == "ativo"'
    groupBy:
      property: note.front
      direction: ASC
    order:
      - note.slug
      - note.repo
      - note.branch
      - note.dirty
      - note.ahead
      - note.behind
      - note.port
      - note.last_savepoint
      - note.updated_at
  - type: table
    name: Tabela
    filters: 'status == "ativo"'
    groupBy:
      property: note.front
      direction: ASC
    order:
      - note.slug
      - note.repo
      - note.branch
      - note.front
      - note.dirty
      - note.ahead
      - note.behind
      - note.updated_at
  - type: table
    name: Removidos
    filters: 'status == "removido"'
    order:
      - note.slug
      - note.repo
      - note.branch
      - note.sha
      - note.last_savepoint
      - note.updated_at
`

func writeVaultViews(dir string, st *State) error {
	basePath := filepath.Join(dir, "worktrees.base")
	if !exists(basePath) {
		f, err := os.OpenFile(basePath, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0644)
		if err != nil {
			return err
		}
		_, err = f.WriteString(strings.ReplaceAll(baseTemplate, "{{folder}}", vaultFolder))
		closeErr := f.Close()
		if err != nil {
			return err
		}
		if closeErr != nil {
			return closeErr
		}
	}
	nodes := []map[string]any{}
	edges := []map[string]any{}
	row := 0
	for _, f := range st.Features {
		for _, w := range f.Worktrees {
			c := w.Connection
			if c == nil {
				continue
			}
			id := noteName(w)
			values := []string{c.Front, "[[" + c.Note + "]]", c.LastSavepoint}
			for col, value := range values {
				node := map[string]any{"id": fmt.Sprintf("%s-%d", id, col), "x": col * 440, "y": row * 220, "width": 340, "height": 160}
				if value == "" {
					node["type"] = "text"
					if col == 0 {
						node["text"] = "Frente não vinculada"
					} else {
						node["text"] = "Sem savepoint vinculado"
					}
					node["color"] = "2"
				} else {
					note := strings.TrimSuffix(strings.TrimPrefix(value, "[["), "]]")
					file, subpath, _ := strings.Cut(note, "#")
					node["type"] = "file"
					node["file"] = strings.TrimSuffix(file, ".md") + ".md"
					if subpath != "" {
						node["subpath"] = "#" + subpath
					}
				}
				nodes = append(nodes, node)
				if col > 0 {
					edges = append(edges, map[string]any{"id": fmt.Sprintf("%s-edge-%d", id, col), "fromNode": fmt.Sprintf("%s-%d", id, col-1), "fromSide": "right", "toNode": fmt.Sprintf("%s-%d", id, col), "toSide": "left"})
				}
			}
			row++
		}
	}
	canvas := map[string]any{"nodes": nodes, "edges": edges, "_generated_by": generatedBy}
	dest := filepath.Join(dir, "worktrees.canvas")
	if exists(dest) {
		if isLink(dest) {
			return fmt.Errorf("Canvas não pode ser link")
		}
		b, err := os.ReadFile(dest)
		if err != nil {
			return err
		}
		var previous map[string]any
		if json.Unmarshal(b, &previous) != nil || previous["_generated_by"] != generatedBy {
			return fmt.Errorf("Canvas existente não pertence ao wt; mantido")
		}
	}
	b, err := json.MarshalIndent(canvas, "", "  ")
	if err != nil {
		return err
	}
	return writeFileIfChanged(dir, dest, b, ".canvas-*.tmp")
}
